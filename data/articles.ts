export const categoryById = (id: string) => categories.find((c) => c.id === id);

type Seed = Omit<Article, "slug" | "status" | "author" | "body"> & {
  slug?: string;
  status?: Article["status"];
  author?: string;
  body?: string[];
};

const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function a(x: Seed): Article {
  return {
    slug: x.slug ?? slugify(x.title),
    status: x.status ?? "published",
    author: x.author ?? "NPFTV Newsroom",
    body: x.body ?? [
      x.summary,
      "NPFTV will report further details as they are confirmed. All information in this story has been verified with the relevant command.",
    ],
    ...x,
  } as Article;
}

